// Helpers for the checklist library (pure functions, no Firebase).
//
// A checklist item is { id, label, details?, required, group? }.
//   label: the document type (e.g. "Oath of Office"); details: what exactly is needed
//   (e.g. "Certified copy of Oath of Office"). Older checklists have the whole text in label.
//   required: true  -> the paper checklist has only a "Y" box: must always be attached.
//   required: false -> "Y" and "N/A" boxes: attach if applicable.
// A document stores the answer per item id: 'Y' (attached) or 'NA' (not applicable).

export const CHECKLIST_CATEGORIES = [
  'Payroll through ATM (Group)',
  'Individual Payment of Salaries and Benefits',
  'Cash Advance',
  'Fund Transfer',
  'Reimbursement',
  'Payment of Other Expenses',
  'Payment to Supplier (Procurement)',
  'Remittance of Withheld Amounts',
  'Refund',
  'Other Disbursements',
  'Liquidation',
];

export const CHECKLIST_SOURCES = [
  { value: 'own', label: 'Own checklist (set in the Checklist tab)' },
  { value: 'disbursement', label: 'Disbursement checklist library (ask the transaction type)' },
  { value: 'liquidation', label: 'Liquidation checklist library (ask the transaction type)' },
];

// Other names of the DMS formats as checklists write them. A checklist item accepts a document
// whose format name (or one of these) appears in the item's document type or details, e.g.
// "Obligation Request" (details: "Or Fund Utilization Report and Status") accepts OBR and FURS.
const ALIASES = {
  OBR: ['Obligation Request', 'OBR'],
  FURS: ['Fund Utilization Report', 'Fund Utilization Request', 'FURS'],
  DV: ['Disbursement Voucher'],
  PR: ['Purchase Request', 'Purchase Requisition'],
  PO: ['Purchase Order'],
  JO: ['Job Order'],
  PCV: ['Petty Cash Voucher'],
  LR: ['Liquidation Report'],
  IT: ['Itinerary of Travel'],
  PAYROLL: ['Payroll'],
};
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Short code of what a checklist item asks for (e.g. "PR" for Purchase Request), for file names;
// the document type itself when DMS has no format for it.
export function itemTypeCode(item) {
  const label = String(item?.label || '');
  const names = { ...ALIASES, ...PIM_DOCS };
  const code = Object.keys(names).find((k) => names[k].some((n) => new RegExp(`\\b${escapeRe(n)}\\b`, 'i').test(label)));
  return code || label;
}

// Property and supply documents generated by PIM (PMS-IMS), not by DMS.
const PIM_DOCS = {
  AIR: ['Acceptance and Inspection Report', 'AIR'],
  CAR: ['Completion and Acceptance Report', 'CAR'],
  PAR: ['Property Acknowledgement Receipt', 'Property Acknowledgment Receipt', 'PAR'],
  ICS: ['Inventory Custodian Slip', 'ICS'],
  RIS: ['Requisition and Issue Slip', 'RIS'],
  PTR: ['Property Transfer Report', 'PTR'],
  ITR: ['Inventory Transfer Report', 'ITR'],
  WMR: ['Waste Material Report', 'WMR'],
  'PRE-POST INSPECTION': ['Pre/Post Inspection Report', 'Pre-Inspection', 'Post-Inspection', 'Pre and Post Inspection'],
  'HISTORY OF REPAIR': ['History of Repair'],
  RSMI: ['Report of Supplies and Materials Issued', 'RSMI'],
};

// The system a checklist item's document comes from when it is not in DMS ('PIM' or '').
export function systemFor(item) {
  const label = String(item?.label || '');
  return Object.values(PIM_DOCS).some((names) => names.some((n) => new RegExp(`\\b${escapeRe(n)}\\b`, 'i').test(label))) ? 'PIM' : '';
}

// (An additional document, not on the checklist (any): any document may be linked to it.)
export function acceptsDocument(item, docu) {
  if (!item || item.any) return true;
  const text = `${item.label || ''} ${item.details || ''}`;
  const names = [...(ALIASES[docu.typeCode] || []), docu.typeName].filter(Boolean);
  return names.some((n) => new RegExp(`\\b${escapeRe(n)}\\b`, 'i').test(text));
}

export const isChecked = (v) => v === true || v === 'Y';

// The Additional documents typed under a checklist (additionalDocs: their names), as items that
// documents are linked or uploaded to like checklist items (links[`add${i}`]).
export const additionalItems = (list = []) => (list || []).map((label, i) => ({ id: `add${i}`, label: String(label || ''), any: true }));

// Printed with separate Document Type and Document Details columns when any item has details.
export const hasDetails = (items) => (items || []).some((i) => String(i.details || '').trim());

export function groupItems(items) {
  const groups = [];
  for (const item of items || []) {
    const name = item.group || '';
    const last = groups[groups.length - 1];
    if (last && last.group === name) last.items.push(item);
    else groups.push({ group: name, items: [item] });
  }
  return groups;
}

// When the type of transaction is changed (e.g. a wrong checklist was picked), answers and
// links carry over to the requirements the new checklist also has (same document type).
export function carryOver(oldItems, newItems, state = {}, links = {}) {
  const key = (i) => String(i.label || '').trim().toLowerCase();
  const before = new Map((oldItems || []).map((i) => [key(i), i.id]));
  const next = { state: {}, links: {} };
  for (const item of newItems || []) {
    const was = before.get(key(item));
    if (!was) continue;
    // An answer of N/A cannot carry over to a requirement that is always required.
    if (state[was] !== undefined && !(item.required && state[was] === 'NA')) next.state[item.id] = state[was];
    if (links[was]?.length) next.links[item.id] = links[was];
  }
  return next;
}

export function missingRequired(items, state) {
  return (items || []).filter((i) => i.required && !isChecked(state?.[i.id]));
}

export function checklistProgress(items, state) {
  const list = items || [];
  const answered = list.filter((i) => isChecked(state?.[i.id]) || state?.[i.id] === 'NA').length;
  return { answered, total: list.length };
}

export function searchChecklists(list, query, kind) {
  const words = String(query || '').toLowerCase().split(/\s+/).filter(Boolean);
  return (list || []).filter((c) => (!kind || c.kind === kind)
    && words.every((w) => `${c.code} ${c.title} ${c.category}`.toLowerCase().includes(w)));
}

// Values for the header boxes of a printed checklist ("DV Number", "Payee", ...),
// taken from the encoded document where the document has them.
const HEADER_KEYS = [
  [/^dv\b|disbursement/i, ['dvNo']],
  [/obr|furs|obligation/i, ['obrNo', 'fursNo', 'obligationNo']],
  [/payee|claimant/i, ['payee', 'claimant', 'name']],
  [/^lr\b|liquidation/i, ['lrNo', 'serialNo']],
];

export function headerValue(label, data = {}) {
  for (const [re, keys] of HEADER_KEYS) {
    if (re.test(label)) {
      const key = keys.find((k) => data[k] !== undefined && String(data[k]).trim() !== '');
      return key ? String(data[key]) : '';
    }
  }
  return '';
}

export function newChecklist(kind = 'disbursement') {
  return {
    code: '', kind, category: kind === 'liquidation' ? 'Liquidation' : CHECKLIST_CATEGORIES[0],
    title: '', description: '', headerFields: kind === 'liquidation'
      ? ['Liquidation Report No.', 'DV Number', 'OBR/FURS Number', 'Payee']
      : ['DV Number', 'OBR/FURS Number', 'Payee'],
    items: [], basis: [], notes: [],
  };
}

// The checklist a document is checked against: the transaction type picked from
// the library (stored on the document), or the document type's own checklist.
export function effectiveChecklist(type, transaction) {
  if (type?.checklistSource && type.checklistSource !== 'own') return transaction || null;
  return {
    code: type?.code || '',
    title: `${type?.name || 'Document'} — Checklist of Requirements`,
    description: '',
    headerFields: [],
    items: (type?.checklist || []).map((c) => ({ id: c.id, label: c.label, details: c.help || '', required: Boolean(c.required) })),
    basis: [],
    notes: [],
  };
}

// What is stored on a document when a transaction type is chosen (frozen copy).
export function transactionSnapshot(c) {
  const { id, updatedAt, updatedBy, createdAt, ...rest } = c;
  return rest;
}
